import assert from 'node:assert/strict';
import { normalizeMobile, mobileEntitlement } from '../src/lib/mobileTrial.ts';
const start = '2026-11-04T00:00:00.000Z';
const now = Date.parse(start);
assert.equal(normalizeMobile('(51) 98583-9571'), '+5551985839571');
assert.equal(normalizeMobile('+55 51 98583-9571'), '+5551985839571');
assert.throws(() => normalizeMobile('+1 555 1234567'));
assert.equal(mobileEntitlement({}, now, null).has_access, false);
assert.equal(mobileEntitlement({}, now, null).verification_required, true);
assert.equal(mobileEntitlement({}, now, { eligible: false, trial_started_at: null }).has_access, false);
const claim = { eligible: true, trial_started_at: start };
assert.equal(mobileEntitlement({}, now, claim).trial_hours_remaining, 48);
assert.equal(mobileEntitlement({}, now + 48 * 3600000, claim).has_access, false);
assert.equal(mobileEntitlement({ trial_started_at: start }, now + 3600000, claim).trial_hours_remaining, 47);
const paid = { subscription: { plan: 'annual' as const, status: 'active' as const, started_at: start, updated_at: start, expires_at: '2027-11-04T00:00:00.000Z' } };
assert.equal(mobileEntitlement(paid, now, null).has_access, true);
assert.equal(mobileEntitlement(paid, now, { eligible: false, trial_started_at: null }).has_access, true);
assert.equal(mobileEntitlement({ ...paid, subscription: { ...paid.subscription, status: 'refunded' } }, now, claim).has_access, false);
console.log('Mobile trial rules passed (11 assertions).');